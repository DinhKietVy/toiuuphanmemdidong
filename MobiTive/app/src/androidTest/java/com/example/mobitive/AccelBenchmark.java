/**
 * M8 (mục 4) — paper 2 on this device: every model variant (3 architectures ×
 * fp32/fp16/dynamic/int8) on every backend (CPU 1/2/4 threads with XNNPACK,
 * CPU without XNNPACK, GPU fp32/fp16, NNAPI). For each pair it measures
 * init time, latency over the real test set, and ON-DEVICE accuracy/F1 on the
 * 112 labelled test vectors, plus agreement with the desktop TFLite output.
 *
 * Models and test vectors live in the TEST APK (androidTest/assets/accel),
 * generated by MobiTiveAI/scripts/export_model_variants.py.
 *
 * Arguments: accelPasses (timed passes over the test set) [3], accelWarmup [10],
 *            backends (comma list or "all") [all], runId.
 */
@RunWith(AndroidJUnit4.class)
public class AccelBenchmark {

    private static final String TAG = "MobiTiveAccel";
    private static final String ASSET_DIR = "accel";
    private static final String[] ALL_BACKENDS = {
            "cpu1", "cpu2", "cpu4", "cpu1_noxnnpack", "gpu_fp32", "gpu_fp16", "nnapi"};

    static final String HEADER = "epoch_ms,device,soc,android_sdk,variant,arch,quant,backend,threads,"
            + "model_bytes,init_ms,warmup,timed_runs,p50_ms,p95_ms,mean_ms,thread_cpu_mean_ms,"
            + "accuracy,precision,recall,f1,tp,fp,tn,fn,agreement_with_desktop,"
            + "max_prob_delta_vs_desktop,thermal_status,status,error";

    @Test
    public void runAllVariantsOnAllBackends() throws Exception {
        Bundle args = InstrumentationRegistry.getArguments();
        Context target = InstrumentationRegistry.getInstrumentation().getTargetContext();
        AssetManager testAssets = InstrumentationRegistry.getInstrumentation().getContext().getAssets();

        int passes = Integer.parseInt(args.getString("accelPasses", "3"));
        int warmup = Integer.parseInt(args.getString("accelWarmup", "10"));
        String runId = args.getString("runId", String.valueOf(System.currentTimeMillis()));
        String backendSpec = args.getString("backends", "all");
        List<String> backends = "all".equalsIgnoreCase(backendSpec)
                ? Arrays.asList(ALL_BACKENDS) : Arrays.asList(backendSpec.split(","));

        TestSet testSet = TestSet.load(testAssets.open(ASSET_DIR + "/test_vectors.bin"));
        Map<String, float[]> desktop = loadDesktopPredictions(testAssets.open(ASSET_DIR + "/desktop_pred.csv"));
        String[] files = testAssets.list(ASSET_DIR + "/models");
        assertTrue("Thiếu model trong androidTest/assets/accel/models — chạy export_model_variants.py",
                files != null && files.length > 0);
        Arrays.sort(files);

        String device = (Build.MANUFACTURER + "_" + Build.MODEL).replaceAll("[^A-Za-z0-9]+", "_");
        File out = new File(target.getExternalFilesDir("results"), "accel_" + device + "_" + runId + ".csv");
        boolean gpuSupported = isGpuSupported();
        log(String.format(Locale.US, "Accel: %d models x %d backends, %d test vectors, GPU supported=%b",
                files.length, backends.size(), testSet.n, gpuSupported));

        int errors = 0;
        try (Writer w = new FileWriter(out)) {
            w.write(HEADER + "\n");
            for (String file : files) {
                String variant = file.replace(".tflite", "");
                ByteBuffer model = readDirect(testAssets.open(ASSET_DIR + "/models/" + file));
                for (String backend : backends) {
                    String row = measure(target, variant, model, backend.trim(), gpuSupported,
                            testSet, desktop.get(variant), warmup, passes);
                    if (row.contains(",ERROR,")) errors++;
                    w.write(row + "\n");
                    w.flush();
                }
            }
        }
        log("Accel DONE errors=" + errors + " csv=" + out.getAbsolutePath());
        // Unsupported backend/model pairs are expected results (status SKIP/ERROR), not test failures.
    }

    private String measure(Context ctx, String variant, ByteBuffer model, String backend,
                           boolean gpuSupported, TestSet ts, float[] desktopProbs,
                           int warmup, int passes) {
        String[] parts = variant.replace("mobitive_", "").split("_");
        String arch = parts[0];
        String quant = parts.length > 1 ? parts[1] : "";
        int threads = backend.startsWith("cpu") ? Integer.parseInt(backend.substring(3, 4)) : 1;
        String prefix = String.format(Locale.US, "%d,%s,%s,%d,%s,%s,%s,%s,%d,%d,",
                System.currentTimeMillis(), q(Build.MANUFACTURER + " " + Build.MODEL), q(soc()),
                Build.VERSION.SDK_INT, q(variant), arch, quant, backend, threads, model.capacity());
        int thermal = thermal(ctx);

        if (backend.startsWith("gpu") && !gpuSupported) {
            log(variant + " " + backend + ": SKIP (GPU delegate not supported)");
            return prefix + ",,,,,,,,,,,,,,,,," + thermal + ",SKIP," + q("GPU delegate not supported on device");
        }

        Delegate delegate = null;
        Interpreter interpreter = null;
        try {
            Interpreter.Options options = new Interpreter.Options().setNumThreads(threads);
            switch (backend) {
                case "cpu1_noxnnpack":
                    options.setUseXNNPACK(false);
                    break;
                case "gpu_fp32":
                case "gpu_fp16": {
                    GpuDelegate.Options o = new GpuDelegate.Options();
                    o.setPrecisionLossAllowed(backend.equals("gpu_fp16"));
                    delegate = new GpuDelegate(o);
                    options.addDelegate(delegate);
                    break;
                }
                case "nnapi":
                    delegate = new NnApiDelegate();
                    options.addDelegate(delegate);
                    break;
                default:
                    if (!backend.matches("cpu[124]")) throw new IllegalArgumentException("backend " + backend);
                    options.setUseXNNPACK(true);
            }

            long t0 = SystemClock.elapsedRealtimeNanos();
            model.rewind();
            interpreter = new Interpreter(model, options);
            double initMs = (SystemClock.elapsedRealtimeNanos() - t0) / 1e6;

            if (interpreter.getInputTensor(0).dataType() != DataType.FLOAT32
                    || interpreter.getOutputTensor(0).dataType() != DataType.FLOAT32) {
                throw new IllegalStateException("model I/O must be float32");
            }
            boolean seq = interpreter.getInputTensor(0).shape().length == 3;
            Object[] inputs = new Object[ts.n];
            for (int i = 0; i < ts.n; i++) {
                inputs[i] = seq ? new float[][][]{{ts.rows[i]}} : new float[][]{ts.rows[i]};
            }
            float[][] output = new float[1][2];

            for (int i = 0; i < warmup; i++) interpreter.run(inputs[i % ts.n], output);

            // Accuracy pass (also first timed pass).
            float[] probs = new float[ts.n];
            List<Double> samples = new ArrayList<>(ts.n * passes);
            double cpuTotal = 0;
            for (int p = 0; p < passes; p++) {
                for (int i = 0; i < ts.n; i++) {
                    long c = Debug.threadCpuTimeNanos();
                    long s = SystemClock.elapsedRealtimeNanos();
                    interpreter.run(inputs[i], output);
                    samples.add((SystemClock.elapsedRealtimeNanos() - s) / 1e6);
                    cpuTotal += (Debug.threadCpuTimeNanos() - c) / 1e6;
                    if (p == 0) probs[i] = output[0][1];
                }
            }

            int tp = 0, fp = 0, tn = 0, fn = 0, agree = 0;
            double maxDelta = 0;
            for (int i = 0; i < ts.n; i++) {
                boolean pred = probs[i] > 0.5f;
                boolean label = ts.labels[i] == 1;
                if (pred && label) tp++; else if (pred) fp++; else if (label) fn++; else tn++;
                if (desktopProbs != null) {
                    if ((desktopProbs[i] > 0.5f) == pred) agree++;
                    maxDelta = Math.max(maxDelta, Math.abs(desktopProbs[i] - probs[i]));
                }
            }
            double precision = tp + fp == 0 ? 0 : tp / (double) (tp + fp);
            double recall = tp + fn == 0 ? 0 : tp / (double) (tp + fn);
            double f1 = precision + recall == 0 ? 0 : 2 * precision * recall / (precision + recall);
            Collections.sort(samples);
            double mean = 0;
            for (double v : samples) mean += v;
            mean /= samples.size();

            String row = prefix + String.format(Locale.US,
                    "%.3f,%d,%d,%.4f,%.4f,%.4f,%.4f,%.5f,%.5f,%.5f,%.5f,%d,%d,%d,%d,%s,%s,%d,OK,",
                    initMs, warmup, samples.size(), pct(samples, .5), pct(samples, .95), mean,
                    cpuTotal / samples.size(), (tp + tn) / (double) ts.n, precision, recall, f1,
                    tp, fp, tn, fn,
                    desktopProbs == null ? "" : String.format(Locale.US, "%.5f", agree / (double) ts.n),
                    desktopProbs == null ? "" : String.format(Locale.US, "%.6f", maxDelta), thermal);
            log(String.format(Locale.US, "%-24s %-15s init %7.1f ms  p50 %7.3f ms  acc %.4f  agree %s",
                    variant, backend, initMs, pct(samples, .5), (tp + tn) / (double) ts.n,
                    desktopProbs == null ? "-" : String.format(Locale.US, "%.3f", agree / (double) ts.n)));
            return row;
        } catch (Throwable e) {
            String msg = e.getClass().getSimpleName() + ": " + (e.getMessage() == null ? "" : e.getMessage());
            log(variant + " " + backend + ": ERROR " + msg);
            return prefix + ",,,,,,,,,,,,,,,,," + thermal + ",ERROR," + q(msg.split("\n")[0]);
        } finally {
            if (interpreter != null) interpreter.close();
            if (delegate instanceof GpuDelegate) ((GpuDelegate) delegate).close();
            if (delegate instanceof NnApiDelegate) ((NnApiDelegate) delegate).close();
        }
    }

    // ------------------------------------------------------------------ data

    static final class TestSet {
        final int n;
        final int dim;
        final int[] labels;
        final float[][] rows;

        private TestSet(int n, int dim, int[] labels, float[][] rows) {
            this.n = n; this.dim = dim; this.labels = labels; this.rows = rows;
        }

        /** Format written by export_model_variants.py (bit-packed, LSB-first). */
        static TestSet load(InputStream in) throws IOException {
            ByteBuffer b = ByteBuffer.wrap(readAll(in)).order(ByteOrder.LITTLE_ENDIAN);
            byte[] magic = new byte[4];
            b.get(magic);
            if (!"MTV1".equals(new String(magic, StandardCharsets.US_ASCII))) {
                throw new IOException("test_vectors.bin: bad magic");
            }
            int n = b.getInt();
            int dim = b.getInt();
            int[] labels = new int[n];
            for (int i = 0; i < n; i++) labels[i] = b.get() & 0xFF;
            int rowBytes = (dim + 7) / 8;
            float[][] rows = new float[n][dim];
            for (int i = 0; i < n; i++) {
                byte[] packed = new byte[rowBytes];
                b.get(packed);
                for (int j = 0; j < dim; j++) {
                    rows[i][j] = ((packed[j >> 3] >> (j & 7)) & 1) == 1 ? 1f : 0f;
                }
            }
            return new TestSet(n, dim, labels, rows);
        }
    }

    private static Map<String, float[]> loadDesktopPredictions(InputStream in) throws IOException {
        Map<String, List<float[]>> tmp = new HashMap<>();
        try (BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
            String line = r.readLine(); // header: variant,index,label,p_malware
            while ((line = r.readLine()) != null) {
                String[] c = line.split(",");
                tmp.computeIfAbsent(c[0], k -> new ArrayList<>())
                        .add(new float[]{Integer.parseInt(c[1]), Float.parseFloat(c[3])});
            }
        }
        Map<String, float[]> out = new HashMap<>();
        for (Map.Entry<String, List<float[]>> e : tmp.entrySet()) {
            float[] probs = new float[e.getValue().size()];
            for (float[] v : e.getValue()) probs[(int) v[0]] = v[1];
            out.put(e.getKey(), probs);
        }
        return out;
    }

    private static ByteBuffer readDirect(InputStream in) throws IOException {
        byte[] bytes = readAll(in);
        ByteBuffer buffer = ByteBuffer.allocateDirect(bytes.length).order(ByteOrder.nativeOrder());
        buffer.put(bytes);
        buffer.rewind();
        return buffer;
    }

    private static byte[] readAll(InputStream in) throws IOException {
        try (InputStream input = in) {
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            byte[] buf = new byte[64 * 1024];
            int n;
            while ((n = input.read(buf)) != -1) out.write(buf, 0, n);
            return out.toByteArray();
        }
    }

    // ------------------------------------------------------------------ misc

    private static boolean isGpuSupported() {
        try (CompatibilityList list = new CompatibilityList()) {
            return list.isDelegateSupportedOnThisDevice();
        } catch (Throwable t) {
            return false;
        }
    }

    private static int thermal(Context ctx) {
        PowerManager pm = (PowerManager) ctx.getSystemService(Context.POWER_SERVICE);
        return pm == null ? -1 : pm.getCurrentThermalStatus();
    }

    private static String soc() {
        return Build.VERSION.SDK_INT >= 31 ? Build.SOC_MANUFACTURER + " " + Build.SOC_MODEL : Build.HARDWARE;
    }

    private static double pct(List<Double> sorted, double p) {
        int index = Math.max(0, (int) Math.ceil(p * sorted.size()) - 1);
        return sorted.get(index);
    }

    private static String q(String s) {
        return '"' + (s == null ? "" : s.replace("\"", "\"\"")) + '"';
    }

    private static void log(String message) {
        Log.i(TAG, message);
        Bundle status = new Bundle();
        status.putString("stream", message + "\n");
        InstrumentationRegistry.getInstrumentation().sendStatus(2, status);
    }
}
